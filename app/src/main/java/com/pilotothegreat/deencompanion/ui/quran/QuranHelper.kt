    fun getMushafPageNumber(surahId: Int, verseId: Int): Int {
        val boundary = pageBoundaries.lastOrNull { b ->
            b.surahNumber < surahId || (b.surahNumber == surahId && b.verseNumber <= verseId)
        }
        return boundary?.pageNumber ?: 1
    }

    @Volatile
    private var cachedSurahs: List<Surah>? = null

    fun cleanArabicText(raw: String): String {
        val normalized = java.text.Normalizer.normalize(raw, java.text.Normalizer.Form.NFC)
        return normalized
            .replace("إِ", "إ")
            .replace("أُ", "أ")
            .replace("أَ", "أ")
            .replace("ءَأَ", "أَأَ")
            .replace("ءَا", "آ")
    }

    fun getSurahs(context: Context): List<Surah> {
        if (cachedSurahs != null) return cachedSurahs!!

        synchronized(this) {
            if (cachedSurahs != null) return cachedSurahs!!

            val json = context.assets.open("quran.json").bufferedReader().use { it.readText() }
            val array = JSONArray(json)
            val surahs = mutableListOf<Surah>()
            for (i in 0 until array.length()) {
                val obj = array.getJSONObject(i)
                val verses = mutableListOf<Verse>()
                val versesArray = obj.getJSONArray("verses")
                for (j in 0 until versesArray.length()) {
                    val vObj = versesArray.getJSONObject(j)
                    verses.add(
                        Verse(
                            id = vObj.getInt("id"),
                            text = cleanArabicText(vObj.getString("text")),
                            translation = vObj.getString("translation")
                        )
                    )
                }
                surahs.add(
                    Surah(
                        id = obj.getInt("id"),
                        name = obj.getString("name"),
                        transliteration = obj.getString("transliteration"),
                        type = obj.getString("type"),
                        totalVerses = obj.getInt("total_verses"),
                        verses = verses
                    )
                )
            }
            cachedSurahs = surahs
            return surahs
        }
    }

    fun getVersesForJuz(context: Context, juzNumber: Int): List<Pair<Surah, Verse>> {
        val surahs = getSurahs(context)
        val juz = juzBoundaries.getOrNull(juzNumber - 1) ?: return emptyList()
        val result = mutableListOf<Pair<Surah, Verse>>()

        for (surah in surahs) {
            if (surah.id < juz.startSurah || surah.id > juz.endSurah) continue

            for (verse in surah.verses) {
                val isInRange = when {
                    surah.id == juz.startSurah && surah.id == juz.endSurah ->
                        verse.id >= juz.startVerse && verse.id <= juz.endVerse
                    surah.id == juz.startSurah -> verse.id >= juz.startVerse
                    surah.id == juz.endSurah -> verse.id <= juz.endVerse
                    else -> true
                }
                if (isInRange) {
                    result.add(Pair(surah, verse))
                }
            }
        }

        return result
    }

    fun isSajdahVerse(surahId: Int, verseId: Int): Boolean {
        return when (surahId) {
            7 -> verseId == 206
            13 -> verseId == 15
            16 -> verseId == 50
            17 -> verseId == 109
            19 -> verseId == 58
            22 -> verseId == 18 || verseId == 77
            25 -> verseId == 60
            27 -> verseId == 26
            32 -> verseId == 15
            38 -> verseId == 24
            41 -> verseId == 38
            53 -> verseId == 62
            84 -> verseId == 21
            96 -> verseId == 19
            else -> false
        }
    }

    fun getSajdahVerses(context: Context): List<Pair<Surah, Verse>> {
        val surahs = getSurahs(context)
        val result = mutableListOf<Pair<Surah, Verse>>()
        for (surah in surahs) {
            for (verse in surah.verses) {
                if (isSajdahVerse(surah.id, verse.id)) {
                    result.add(Pair(surah, verse))
                }
            }
        }
        return result
    }
